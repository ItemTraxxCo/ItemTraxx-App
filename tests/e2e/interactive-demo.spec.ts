import { test, expect } from '@playwright/test';

test('guided demo completes with local sample data', async ({ page }) => {
  await page.goto('/demo');
  const consent = page.getByRole('button', { name: 'Essential only' });
  await consent.click();
  const guide = page.locator('aside.guide');
  await expect(guide.getByRole('heading', { name: 'Look up a borrower' })).toBeVisible();
  await expect(guide.getByText('GUIDED PRODUCT TOUR')).toHaveCount(0);
  await expect(page.locator('.workspace-nav')).toHaveCount(0);
  const insert = guide.getByRole('button', { name: 'Insert into field' });
  await insert.hover();
  await expect(insert).toHaveCSS('color', 'rgb(255, 255, 255)');
  expect(await page.locator('main.demo').evaluate(el => el.getBoundingClientRect().bottom)).toBeGreaterThanOrEqual(await page.evaluate(() => window.innerHeight));
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await page.getByRole('button', { name: 'Load borrower' }).click();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await page.getByRole('button', { name: 'Add barcode' }).click();
  await page.getByRole('button', { name: 'Complete transaction' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Transaction processing...');
  const toastBox = await page.locator('.demo-toast').boundingBox();
  const workspaceBox = await page.getByRole('region', { name: 'Demo workspace' }).boundingBox();
  expect(toastBox!.x + toastBox!.width).toBeLessThanOrEqual(workspaceBox!.x + workspaceBox!.width);
  expect(await page.evaluate(() => window.innerHeight) - (toastBox!.y + toastBox!.height)).toBeLessThan(40);
  await expect(page.getByRole('button', { name: 'Complete transaction' })).toBeDisabled();
  await expect(guide.getByRole('button', { name: 'Back' })).toBeDisabled();
  await expect(page.locator('.demo-toast')).toContainText('1 checkout(s)');
  await expect(page.getByPlaceholder('Enter borrower ID')).toHaveValue('');
  await expect(guide.getByRole('heading', { name: 'Look up the borrower again' })).toBeVisible();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await page.getByRole('button', { name: 'Load borrower' }).click();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await page.getByRole('button', { name: 'Add barcode' }).click();
  await page.getByRole('button', { name: 'Complete transaction' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Transaction processing...');
  await expect(page.getByRole('button', { name: 'Complete transaction' })).toBeDisabled();
  await expect(page.locator('.demo-toast')).toContainText('1 return(s)');
  await guide.getByRole('button', { name: /Continue/ }).click();
  await page.getByRole('button', { name: 'Specific Tenant Accounts' }).click();
  await page.getByRole('button', { name: 'staff@example.com' }).click();
  await page.getByRole('button', { name: 'Add borrower' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Borrower added.');
  await page.getByRole('button', { name: 'Details' }).click();
  const borrowerDialog = page.getByRole('dialog', { name: 'Borrower details' });
  await expect(borrowerDialog).toBeVisible();
  const backdrop = (await page.locator('.demo-modal-backdrop').boundingBox())!;
  const guideBox = (await guide.boundingBox())!;
  expect(backdrop.x + backdrop.width).toBeLessThanOrEqual(guideBox.x + 1);
  expect((await borrowerDialog.boundingBox())!.y).toBeGreaterThanOrEqual(0);
  await borrowerDialog.getByRole('button', { name: 'Archive borrower' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Borrower archived');
  await page.locator('.demo-toast').getByRole('button', { name: 'Undo' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Borrower restored.');
  await page.getByRole('button', { name: 'Archive borrower' }).click();
  await expect(guide.getByRole('heading', { name: 'Borrower management complete' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Borrower Management', exact: true })).toBeVisible();
  await guide.getByRole('button', { name: /Continue/ }).click();
  await expect(page.getByRole('heading', { name: 'Item Management', exact: true })).toBeVisible();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await expect(guide.getByRole('heading', { name: 'Enter a barcode' })).toBeVisible();
  await guide.getByRole('button', { name: 'Back' }).click();
  await expect(guide.getByRole('heading', { name: 'Add an item', exact: true })).toBeVisible();
  await expect(page.getByPlaceholder('Item name')).toHaveValue('');
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await page.getByRole('button', { name: 'Add item' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Item added.');
  await page.getByRole('button', { name: 'Details' }).click();
  const itemDialog = page.getByRole('dialog', { name: 'Item details' });
  await expect(itemDialog).toBeVisible();
  await expect(itemDialog.getByLabel('Serial Number')).toHaveValue('SN-2002');
  await expect(itemDialog.getByLabel('Notes')).toHaveValue('Includes charging cable');
  const itemBackdrop = (await page.locator('.demo-modal-backdrop').boundingBox())!;
  expect(itemBackdrop.x + itemBackdrop.width).toBeLessThanOrEqual((await guide.boundingBox())!.x + 1);
  await itemDialog.getByRole('button', { name: 'Edit item' }).click();
  await guide.getByRole('button', { name: 'Insert into field' }).click();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('.demo-toast')).toContainText('Item updated.');
  await page.getByRole('button', { name: 'Archive item' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Item archived');
  await page.locator('.demo-toast').getByRole('button', { name: 'Undo' }).click();
  await expect(page.locator('.demo-toast')).toContainText('Item restored.');
  await page.getByRole('button', { name: 'Archive item' }).click();
  await expect(page.getByRole('heading', { name: 'Item Logs', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Checkout', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Return', exact: true })).toBeVisible();
  await guide.getByRole('button', { name: /Finish demo/ }).click();
  await expect(guide.getByRole('heading', { name: 'You completed the demo!' })).toBeVisible();
  await expect(guide.getByText('This demo uses sample data.', { exact: false })).toBeVisible();
  await expect(guide.locator('.celebration')).toHaveCount(0);
  await expect(guide.getByRole('link', { name: /Contact us/ })).toHaveAttribute('href', '/request-demo');
  await guide.getByRole('button', { name: 'Explore on your own' }).click();
  await expect(page.getByRole('heading', { name: 'Explore on your own' })).toBeVisible();
  const roam = page.locator('.roam');
  await roam.getByRole('button', { name: 'Borrowers', exact: true }).click();
  await roam.getByRole('button', { name: 'Specific Tenant Accounts' }).click();
  await expect(roam.getByRole('button', { name: 'Add borrower' })).toBeDisabled();
  await roam.getByRole('button', { name: 'staff@example.com' }).click();
  await roam.getByRole('button', { name: 'Add borrower' }).click();
  await expect(roam.getByRole('cell', { name: 'staff@example.com' })).toBeVisible();
  await roam.getByRole('row', { name: /silver-otter/ }).getByRole('button', { name: 'Archive' }).click();
  await roam.getByRole('button', { name: 'Restore' }).click();
  await expect(roam.getByRole('row', { name: /silver-otter/ })).toBeVisible();
  await roam.getByRole('button', { name: 'Items', exact: true }).click();
  await roam.getByRole('button', { name: 'Add item', exact: true }).click();
  await expect(roam.getByRole('cell', { name: 'SN-2002' })).toBeVisible();
  await roam.getByRole('row', { name: /Tablet.*IT-2002/ }).getByRole('button', { name: 'Details' }).click();
  await roam.getByLabel('Item details').getByLabel('Name').selectOption('Tablet Pro');
  await roam.getByLabel('Item details').getByRole('button', { name: 'Save' }).click();
  await expect(roam.getByRole('cell', { name: 'Tablet Pro' })).toBeVisible();
  await roam.getByRole('button', { name: 'Checkout and return' }).click();
  await roam.getByLabel('Borrower ID').selectOption('BR-1001');
  await roam.getByLabel('Item barcode').selectOption('IT-2002');
  await roam.getByRole('button', { name: 'Complete transaction' }).click();
  await expect(roam.getByRole('button', { name: 'Items', exact: true })).toBeDisabled();
  await expect(roam.getByRole('status')).toHaveText('Transaction complete.');
  await roam.getByRole('button', { name: 'Items', exact: true }).click();
  await roam.getByRole('row', { name: /Tablet Pro.*IT-2002/ }).getByRole('button', { name: 'Details' }).click();
  await expect(roam.getByRole('button', { name: 'Archive item' })).toBeDisabled();
  await roam.getByRole('button', { name: 'Checkout and return' }).click();
  await roam.getByLabel('Borrower ID').selectOption('BR-1001');
  await roam.getByLabel('Item barcode').selectOption('IT-2002');
  await roam.getByRole('button', { name: 'Complete transaction' }).click();
  await expect(roam.getByRole('status')).toHaveText('Transaction complete.');
  await roam.getByRole('button', { name: 'Item logs' }).click();
  await expect(roam.getByRole('cell', { name: 'Checkout', exact: true })).toBeVisible();
  await expect(roam.getByRole('cell', { name: 'Return', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Return to completion' }).click();
  await guide.getByRole('button', { name: 'Back' }).click();
  await expect(guide.getByRole('heading', { name: 'Review item logs' })).toBeVisible();
});
